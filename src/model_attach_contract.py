"""Opt-in ZERO-output adapter attachment AFTER strict legacy visual load.

This contract does not itself load 26GB weights, approve candidate data, train a
VLA, patch the real deploy server, or advertise tactile_v1. The caller must use
an isolated module generated by patch_model_v2 and supply an actual strict
load_state_dict result or a complete verified StrictStreamResult, not a boolean.
"""
from __future__ import annotations

import torch
from torch.nn.modules.module import _IncompatibleKeys
from strict_stream_visual_weights import StrictStreamResult
from tactile_adapter import TactileStateResidual


def attach_visual_identity_adapter(model, strict_load_result):
    """Attach trainable tactile residual only after exact old-checkpoint load.

    Inspect the original state_dict BEFORE new keys exist. A missing/extra key
    in strict_load_result is a hard error; checkpoint/source provenance remains
    separately gated and this helper never enables deployment or model fitting.
    """
    if not isinstance(model, torch.nn.Module):
        raise ValueError('requires patched V2 visual model strictly loaded without adapter')
    # Original LingbotVlaV2Policy wraps FlowMatchingV2 at .model: the 154800
    # checkpoint covers the WHOLE wrapper, whereas the state-token hook lives
    # ONLY on that inner module. Small CPU contract tests also use the inner
    # FlowMatchingV2-like module directly.
    inner=getattr(model,'model',None)
    core=(inner if isinstance(inner,torch.nn.Module) and not hasattr(model,'state_proj')
          else model)
    adapter_prefix=('model.' if core is not model else '')+'tactile_adapter.'
    if (not hasattr(model,'config') or not hasattr(core,'config') or
            getattr(model, '_strict_stream_partial_failure', False) or
            getattr(core, '_strict_stream_partial_failure', False) or
            getattr(model.config, 'tactile_enabled', False) or
            getattr(core.config, 'tactile_enabled', False) or
            getattr(core, 'tactile_adapter', 'MISSING') is not None or
            not callable(getattr(core, '_tactile_delta', None)) or
            not callable(getattr(core, 'sample_actions', None)) or
            not callable(getattr(core, 'predict_velocity', None)) or
            not isinstance(getattr(core,'state_proj',None), torch.nn.Linear) or
            (core is not model and
             (getattr(model,'config',None) is not core.config or
              any(not key.startswith('model.') for key in model.state_dict())))):
        raise ValueError('requires patched V2 visual model strictly loaded without adapter')
    missing=getattr(strict_load_result, 'missing_keys',None)
    extra=getattr(strict_load_result, 'unexpected_keys',None)
    if (not isinstance(strict_load_result,(_IncompatibleKeys,StrictStreamResult)) or
            missing is None or extra is None or missing or extra or
            isinstance(strict_load_result,StrictStreamResult) and (
                strict_load_result.copied_key_count!=len(model.state_dict()) or
                strict_load_result.status!='strict_stream_visual_values_loaded_not_tactile_training' or
                strict_load_result.training_approval is not False)):
        raise ValueError('exact strict old-vision checkpoint load result required')
    if any(k.startswith(adapter_prefix) for k in model.state_dict()):
        raise ValueError('adapter keys present before strict visual checkpoint load')
    for parameter in model.parameters():
        parameter.requires_grad_(False)
    projection=core.state_proj.weight
    adapter=TactileStateResidual(state_width=int(projection.shape[0])).to(
        device=projection.device,dtype=projection.dtype)
    core.tactile_adapter=adapter
    core.config.tactile_enabled=True
    model.config.tactile_enabled=True
    if any(p.requires_grad for name,p in model.named_parameters() if not name.startswith(adapter_prefix)):
        raise AssertionError('base backbone must remain frozen')
    if not any(p.requires_grad for p in adapter.parameters()):
        raise AssertionError('new adapter has no trainable parameters')
    return {'status':'zero_residual_attachment_only_not_training_or_deployment',
            'training_approval':False,'server_capability_advertised':False,
            'base_parameter_count':sum(p.numel() for name,p in model.named_parameters()
                                       if not name.startswith(adapter_prefix)),
            'adapter_parameter_count':sum(p.numel() for p in adapter.parameters()),
            'dtype':str(projection.dtype),'device_type':projection.device.type}
